#!/usr/bin/env python3
"""Generate src/render/kite_art.{c,h}: M3 Kite Kennel art.

All art is GPT Image (gpt-image-2.6-sunburst) output quantized to GBC
formats. Grids are committed in scripts/kite_art_grids.json; raw renders
stay out of the repo. The cairn is M2's (same graphic, same meaning).

  python3 scripts/gen_kite_art.py                 # JSON -> C
  python3 scripts/gen_kite_art.py --png OUT [s]   # preview sheet
  python3 scripts/gen_kite_art.py --from-gpt RAW  # re-quantize RAW/*.png

BG tiles (VRAM bank 0, over Riftwild-only ids while the pocket is live;
0 lightest .. 3 darkest): cairn 2x2 (98, 109, 110, 39), kennel bars (99),
rift-stream (108), crystal lock left column (37 top, 38 bottom; the right
column is the same tiles X-flipped).
OBJ (VRAM bank 1, 176..203; 0 transparent, 1 body, 2 outline, 3 highlight):
176 Kite flying, 180 Kite breathing, 184 stream plate rock, 188 stream
plate flowing, 192 reset plate (M1), 196 lever shut, 200 lever open.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_rime_art as m1  # noqa: E402
import gen_rewrite_art as m2  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GRIDS = ROOT / "scripts" / "kite_art_grids.json"
BG = (("cairn", 16), ("bars", 8), ("stream", 8), ("lock_l", 0))
BG_IDS = {"cairn": (98, 109, 110, 39), "bars": (99,), "stream": (108,), "lock_l": (37, 38)}
OBJ = (("kite_fly", "kite_fly"), ("kite_breath", "kite_breath"),
       ("s_rock", "glyph_s_rock"), ("s_stream", "glyph_s_stream"),
       ("plate", None), ("l_shut", "glyph_l_shut"), ("l_open", "glyph_l_open"))
TILE0 = {"kite_fly": 176, "kite_breath": 180, "s_rock": 184, "s_stream": 188,
         "plate": 192, "l_shut": 196, "l_open": 200}


def from_gpt(raw):
    import numpy as np
    from PIL import Image

    def load(n):
        return np.array(Image.open(Path(raw) / f"{n}.png").convert("RGB")).astype(float)
    g = {"note": "BG: 0 lightest..3 darkest. OBJ: 0 transparent, 1 body, 2 outline, "
                 "3 highlight. Quantized from gpt-image-2.6-sunburst renders by "
                 "scripts/gen_kite_art.py --from-gpt; cairn and plate reused from M2/M1."}
    g["cairn"] = json.loads(m2.GRIDS.read_text())["cairn"]
    g["bars"] = m2.quant_bg(load("bars8"), 8)
    g["stream"] = m2.quant_bg(load("stream8"), 8)
    lock = m2.quant_bg(load("lock16"), 16)
    g["lock"] = [r[:8] + r[:8][::-1] for r in lock]       # exact left-right mirror
    for name, src in OBJ:
        if src:
            g[name] = m2.quant_obj(load(src), 16)
    g["plate"] = json.loads(m1.GRIDS.read_text())["plate"]
    GRIDS.write_text(json.dumps(g, indent=1))


def emit(g):
    bg = sum((m1.tile_bytes(t) for t in m1.cut(g["cairn"], 2, 2)), [])
    bg += m1.tile_bytes(g["bars"]) + m1.tile_bytes(g["stream"])
    left = [r[:8] for r in g["lock"]]
    bg += m1.tile_bytes(left[:8]) + m1.tile_bytes(left[8:])
    obj = []
    for name, _ in OBJ:
        for t in m1.cut(g[name], 2, 2):
            obj += m1.tile_bytes(t)
    ids = [i for name, _ in BG for i in BG_IDS[name]]
    c = f"""#pragma bank 31
// Generated by scripts/gen_kite_art.py from GPT Image art. Do not edit.
#include <gb/gb.h>
#include "core/types.h"
#include "render/kite_art.h"

{m1.c_array("kt_bg_tiles", bg)}

static const u8 kt_bg_ids[{len(ids)}] = {{ {", ".join(map(str, ids))} }};

{m1.c_array("kt_obj_tiles", obj)}

void kt_bg_art_load(void) BANKED {{
    u8 i;
    VBK_REG = 0;
    for (i = 0; i < {len(ids)}; ++i)
        set_bkg_data(kt_bg_ids[i], 1, kt_bg_tiles + (u16)i * 16);
}}

void kt_art_load(void) BANKED {{
    VBK_REG = 1;
    set_sprite_data(KT_TILE_KITE, {len(obj) // 16}, kt_obj_tiles);
    VBK_REG = 0;
}}
"""
    h = """#ifndef QUINTRA_RENDER_KITE_ART_H
#define QUINTRA_RENDER_KITE_ART_H
// Generated by scripts/gen_kite_art.py. Bank-1 OBJ tiles (2x2 each).
#include <gb/gb.h>
#define KT_TILE_KITE     176
#define KT_TILE_BREATH   180
#define KT_TILE_S_ROCK   184
#define KT_TILE_S_STREAM 188
#define KT_TILE_PLATE    192   // same slot as RW_TILE_PLATE
#define KT_TILE_L_SHUT   196
#define KT_TILE_L_OPEN   200
void kt_bg_art_load(void) BANKED;
void kt_art_load(void) BANKED;
#endif
"""
    (ROOT / "src/render/kite_art.c").write_text(c)
    (ROOT / "src/render/kite_art.h").write_text(h)


BG_PREV = {"cairn": m2.BG_PREV["cairn"],
           "bars": [(200, 200, 210), (120, 120, 140), (60, 60, 80), (16, 16, 24)],
           "stream": [(255, 240, 180), (255, 160, 60), (170, 60, 30), (30, 10, 20)],
           "lock": [(230, 250, 255), (140, 200, 240), (60, 110, 180), (16, 30, 60)]}
KITE = [(0, 0, 0), (240, 120, 40), (40, 16, 16), (255, 230, 120)]
OBJ_PREV = {"kite_fly": KITE, "kite_breath": KITE,
            "s_rock": m1.PREVIEW_PALS["pipes"], "s_stream": m1.PREVIEW_PALS["pipes"],
            "plate": m1.PREVIEW_PALS["plate"],
            "l_shut": m1.PREVIEW_PALS["jagger_idle"], "l_open": m1.PREVIEW_PALS["jagger_idle"]}


def preview(g, out, scale=4):
    from PIL import Image
    im = Image.new("RGB", (7 * 20 + 4, 44), (120, 140, 110))
    for i, name in enumerate(("cairn", "bars", "stream", "lock")):
        n = len(g[name])
        for y in range(16):
            for x in range(16):
                im.putpixel((4 + i * 20 + x, 4 + y), BG_PREV[name][int(g[name][y % n][x % n])])
    for i, (name, _) in enumerate(OBJ):
        for y, row in enumerate(g[name]):
            for x, ch in enumerate(row):
                if ch != "0":
                    im.putpixel((4 + i * 20 + x, 24 + y), OBJ_PREV[name][int(ch)])
    im.resize((im.width * scale, im.height * scale), Image.NEAREST).save(out)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--from-gpt":
        from_gpt(sys.argv[2])
    g = json.loads(GRIDS.read_text())
    if len(sys.argv) > 2 and sys.argv[1] == "--png":
        preview(g, sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
        return
    emit(g)


if __name__ == "__main__":
    main()
