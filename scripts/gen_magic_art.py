out = []
for name in order:
    rows = T[name]
    assert len(rows) == 8, name
    b = []
    for r in rows:
        assert len(r) == 8, (name, r)
        lo = hi = 0
        for x, ch in enumerate(r):
            c = 0 if ch == '.' else int(ch)
            if c & 1: lo |= 0x80 >> x
            if c & 2: hi |= 0x80 >> x
        b += [lo, hi]
    out.append("    /* %-8s */ %s," % (name, ",".join("0x%02X" % v for v in b)))
print("static const u8 magic_art[MAGIC_TILE_COUNT * 16] = {\n" + "\n".join(out) + "\n};")
