#!/usr/bin/env python3
"""Generate src/render/basilisk_art.{c,h}: basilisk tiers + bomb blast (OBJ, VRAM bank 1).

The art is GPT Image (gpt-image-2.6-sunburst) output, quantized to the
4-colour GBC sprite format. The quantized grids are committed in
scripts/basilisk_art_grids.json (colour index 0 transparent, 1 body,
2 outline/dark, 3 highlight); the 1 MB raw renders stay out of the repo.

  python3 scripts/gen_basilisk_art.py                 # JSON -> C
  python3 scripts/gen_basilisk_art.py --png OUT.png   # 6x preview sheet
  python3 scripts/gen_basilisk_art.py --from-gpt RAW  # re-quantize RAW/*.png -> JSON

VRAM bank-1 OBJ layout (only one tier is resident; post_spawn loads it):
  176..191 idle 32x32, 192..207 walk, 10..25 fire/charge (row-major 4x4)
  26..39, 214..215 blast quadrant frames (4 frames x 4 tiles), 216 debris
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRIDS = ROOT / "scripts" / "basilisk_art_grids.json"
POSES = ("idle", "walk", "fire")
POSE_BASE = (176, 192, 10)
BLAST_SLOTS = list(range(26, 40)) + [214, 215]
DEBRIS_SLOT = 216


def tile_bytes(rows):
    out = []
    for row in rows:
        lo = hi = 0
        for x, ch in enumerate(row):
            v = int(ch)
            if v & 1:
                lo |= 0x80 >> x
            if v & 2:
                hi |= 0x80 >> x
        out += [lo, hi]
    return out


def cut(grid, w_tiles, h_tiles):
    tiles = []
    for ty in range(h_tiles):
        for tx in range(w_tiles):
            tiles.append([grid[ty * 8 + y][tx * 8:tx * 8 + 8] for y in range(8)])
    return tiles


def c_array(name, data):
    lines = [f"static const u8 {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def emit(g):
    parts = []
    for t in ("t1", "t2", "t3"):
        data = []
        for p in POSES:
            for tile in cut(g["tiers"][t][p], 4, 4):
                data += tile_bytes(tile)
        parts.append(c_array(f"bas_{t}", data))
    blast = []
    for f in g["blast"]:
        for tile in cut(f, 2, 2):
            blast += tile_bytes(tile)
    parts.append(c_array("bas_blast", blast))
    parts.append(c_array("bas_debris", tile_bytes(g["debris"])))
    parts.append(c_array("bas_blank", [0] * 16))
    c = f"""#pragma bank 255
// Generated by scripts/gen_basilisk_art.py from GPT Image art. Do not edit.
#include <gb/gb.h>
#include "render/basilisk_art.h"

BANKREF(basilisk_art_load)

{chr(10).join(parts)}

/* tier 0..2 loads that basilisk's three 32x32 poses; 0xFF loads only the
   blast. Called from room post-spawn (display may be on: the copy routine
   waits for each VRAM-accessible window). */
void basilisk_art_load(u8 tier) BANKED {{
    const u8 *b = tier == 2 ? bas_t3 : tier == 1 ? bas_t2 : bas_t1;
    VBK_REG = 1;
    if (tier < 3) {{
        set_sprite_data(BAS_TILE_IDLE, 16, b);
        set_sprite_data(BAS_TILE_WALK, 16, b + 256);
        set_sprite_data(BAS_TILE_FIRE, 16, b + 512);
    }}
    set_sprite_data(26, 14, bas_blast);
    set_sprite_data(214, 2, bas_blast + 224);
    set_sprite_data(BLAST_TILE_DEBRIS, 1, bas_debris);
    VBK_REG = 0;
    if (tier < 3) set_sprite_data(BAS_CORE_TILE, 1, bas_blank);  /* bank-0 core */
}}
"""
    h = """// Generated by scripts/gen_basilisk_art.py. Do not edit.
#ifndef QUINTRA_BASILISK_ART_H
#define QUINTRA_BASILISK_ART_H
#include <gb/gb.h>
#include "core/types.h"

/* VRAM bank-1 OBJ tiles (use prop | 0x08). Poses are 4x4 row-major. */
#define BAS_TILE_IDLE     176
#define BAS_TILE_WALK     192
#define BAS_TILE_FIRE     10
#define BLAST_TILE_DEBRIS 216
/* Bank-0 OBJ the basilisk entity itself points at (SPR_ENEMY_LEYBEAM): kept
   blank so the allocator's 8x8 for it draws nothing. */
#define BAS_CORE_TILE     219
/* Blast frame f quadrant tile j (0 TL, 1 TR, 2 BL, 3 BR of the 16x16 quad):
   frames 0..2 at 26 + f*4 + j; frame 3 at 38, 39, 214, 215. */
#define BLAST_TILE(f, j) ((u8)((f) < 3 ? 26 + ((f) << 2) + (j) : ((j) < 2 ? 38 + (j) : 212 + (j))))

BANKREF_EXTERN(basilisk_art_load)
void basilisk_art_load(u8 tier) BANKED;

#endif
"""
    (ROOT / "src/render/basilisk_art.c").write_text(c)
    (ROOT / "src/render/basilisk_art.h").write_text(h)


def preview(g, out):
    from PIL import Image
    pals = {"t1": [(0, 0, 0), (60, 200, 70), (10, 60, 20), (240, 220, 80)],
            "t2": [(0, 0, 0), (230, 50, 40), (60, 10, 10), (250, 230, 90)],
            "t3": [(0, 0, 0), (110, 50, 165), (25, 8, 55), (165, 250, 150)]}
    bp = [(0, 0, 0), (230, 50, 40), (60, 10, 10), (250, 230, 90)]
    im = Image.new("RGB", (3 * 36 + 4, 4 * 36 + 4), (140, 150, 140))
    for r, t in enumerate(("t1", "t2", "t3")):
        for c, p in enumerate(POSES):
            for y, row in enumerate(g["tiers"][t][p]):
                for x, ch in enumerate(row):
                    if ch != "0":
                        im.putpixel((4 + c * 36 + x, 4 + r * 36 + y), pals[t][int(ch)])
    for f, q in enumerate(g["blast"][:3]):
        for y in range(32):
            for x in range(32):
                ch = q[y if y < 16 else 31 - y][x if x < 16 else 31 - x]
                if ch != "0":
                    im.putpixel((4 + f * 36 + x, 4 + 3 * 36 + y), bp[int(ch)])
    im.resize((im.width * 6, im.height * 6), Image.NEAREST).save(out)


def from_gpt(raw):
    """Quantize the GPT renders. Light cleanup only: background/outline/body/
    highlight classes, majority downsample, 1-px silhouette outline."""
    import numpy as np
    from PIL import Image

    def classify(a):
        a = a.astype(int)
        r, g_, b = a[..., 0], a[..., 1], a[..., 2]
        lum = (r * 3 + g_ * 6 + b) / 10
        spread = a.max(-1) - a.min(-1)
        c = np.full(r.shape, 2)
        c[(lum > 225) & (spread < 40)] = 0
        c[lum < 75] = 1
        c[(r > 190) & (g_ > 180) & (b < 170) & (lum <= 245)] = 3
        return c

    def reduce(stack, n, th, edge):
        h, w = stack[0].shape
        out = np.zeros((n, n), int)
        for y in range(n):
            for x in range(n):
                cnt = np.zeros(4)
                for s in stack:
                    blk = s[y * h // n:(y + 1) * h // n, x * w // n:(x + 1) * w // n]
                    cnt += np.bincount(blk.ravel(), minlength=4)
                cnt /= cnt.sum()
                if cnt[0] > (0.6 if edge else 0.55):
                    continue
                if cnt[1] >= th:
                    out[y, x] = 1
                    continue
                nz = cnt.copy()
                nz[0] = 0
                out[y, x] = int(np.argmax(nz)) if (not edge or cnt[0] < 0.5) else 0
        if edge:
            o = out.copy()
            for y in range(n):
                for x in range(n):
                    if not out[y, x]:
                        continue
                    for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                        yy, xx = y + dy, x + dx
                        if not (0 <= yy < n and 0 <= xx < n) or not out[yy, xx]:
                            o[y, x] = 1
            out = o
        return out

    remap = {0: "0", 1: "2", 2: "1", 3: "3"}
    rows = lambda a: ["".join(remap[int(v)] for v in r) for r in a]
    g = {"note": "Colour indices (0 transparent, 1 body, 2 outline/dark, 3 highlight) "
                 "quantized from gpt-image-2.6-sunburst renders by "
                 "scripts/gen_basilisk_art.py --from-gpt.", "tiers": {}}
    for t in ("t1", "t2", "t3"):
        cs = [classify(np.array(Image.open(Path(raw) / f"{t}_{p}.png").convert("RGB"))) for p in POSES]
        m = np.zeros(cs[0].shape, bool)
        for c in cs:
            m |= c != 0
        ys, xs = np.where(m)
        y1, x0, x1 = ys.max() + 1, xs.min(), xs.max() + 1
        s = max(y1 - ys.min(), x1 - x0)
        by0, bx0 = y1 - s, (x0 + x1) // 2 - s // 2
        g["tiers"][t] = {}
        for p, c in zip(POSES, cs):
            pad = np.zeros((c.shape[0] + 2 * s, c.shape[1] + 2 * s), int)
            pad[s:s + c.shape[0], s:s + c.shape[1]] = c
            g["tiers"][t][p] = rows(reduce([pad[by0 + s:by0 + 2 * s, bx0 + s:bx0 + 2 * s]], 32, 0.40, True))
    c = classify(np.array(Image.open(Path(raw) / "blast.png").convert("RGB")))
    cols = np.where((c != 0).any(0))[0]
    runs, s0, p0 = [], cols[0], cols[0]
    for x in cols[1:]:
        if x - p0 > 12:
            runs.append((s0, p0))
            s0 = x
        p0 = x
    runs.append((s0, p0))
    S = 400
    g["blast"] = []
    for x0, x1 in runs[:4]:
        ys = np.where((c[:, x0:x1 + 1] != 0).any(1))[0]
        cy, cx = (ys.min() + ys.max()) // 2, (x0 + x1) // 2
        pad = np.zeros((c.shape[0] + S, c.shape[1] + S), int)
        pad[S // 2:S // 2 + c.shape[0], S // 2:S // 2 + c.shape[1]] = c
        cr = pad[cy:cy + S, cx:cx + S]
        h = S // 2
        quads = [cr[:h, :h], cr[:h, ::-1][:, :h], cr[::-1, :][:h, :h], cr[::-1, ::-1][:h, :h]]
        g["blast"].append(rows(reduce(quads, 16, 0.40, False)))
    x0, x1 = runs[2]
    sub = c[:, x0:x1 + 1]
    ys, xs = np.where(sub == 1)
    sel = (xs < (x1 - x0) * 0.18) & (ys < np.median(ys))
    cy, cx = int(np.median(ys[sel])), int(np.median(xs[sel]))
    g["debris"] = rows(reduce([sub[cy - 36:cy + 36, cx - 36:cx + 36]], 8, 0.3, False))
    GRIDS.write_text(json.dumps(g, indent=1))


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--from-gpt":
        from_gpt(sys.argv[2])
    g = json.loads(GRIDS.read_text())
    if len(sys.argv) > 2 and sys.argv[1] == "--png":
        preview(g, sys.argv[2])
        return
    emit(g)


if __name__ == "__main__":
    main()
