"""Record an attract-mode demo (spec 2026-11-17 attract addendum).

A small bot plays an ordinary run with a fixed class, stage warp and seed in
headless PyBoy. The joypad byte the game actually saw each loop iteration,
from the first room frame on, is saved as (keys, frames) pairs; the ROM
replays them through attract_demo_frame(). Playback is deterministic, so the
recording is real gameplay. Rerun after big gameplay changes if the demo
drifts (scripts/test_attract_mode.py reports the drift).

  python3 scripts/record_attract_demo.py ROM CLASS SEED OUT.json [FRAMES] [WARP]
  python3 scripts/record_attract_demo.py --emit   # JSONs -> attract_demo_data.h
"""
import sys, re, json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEMOS = ["assets/attract/demo_wolfkin_crystal.json", "assets/attract/demo_picsean_verdant.json"]


def emit():
    out = ["// Generated by scripts/record_attract_demo.py --emit. Do not edit by hand.",
           "// Attract-mode demo recordings, included only by src/game/intro.c (bank 22).",
           "// Each demo: class id, stage warp (0xFF = stage 1 foyer), run seed (u16 LE,",
           "// fed to run_init through loop_frame_counter), then (keys, frames) pairs",
           "// ending with (0, 0). Playback is deterministic: same seed, same input.",
           "#ifndef QUINTRA_GAME_ATTRACT_DEMO_DATA_H",
           "#define QUINTRA_GAME_ATTRACT_DEMO_DATA_H", "",
           f"#define ATTRACT_DEMO_COUNT {len(DEMOS)}",
           "#define ATTRACT_DEMO_FRAMES 900u    // loop iterations (~15-25 s), then the title", ""]
    names = []
    for i, rel in enumerate(DEMOS):
        d = json.loads((ROOT / rel).read_text())
        data = [d["class"], d["warp"], d["seed"] & 0xFF, d["seed"] >> 8]
        for k, n in d["pairs"]:
            data += [k, n]
        data += [0, 0]
        assert len(d["pairs"]) < 4000
        names.append(f"attract_demo{i}")
        out.append(f"// {rel}: {d['n']} frames")
        out.append(f"static const u8 attract_demo{i}[{len(data)}] = {{")
        for j in range(0, len(data), 16):
            out.append("    " + ", ".join(f"0x{v:02X}" for v in data[j:j + 16]) + ",")
        out.append("};")
    out += ["", "static const u8 * const attract_demos[ATTRACT_DEMO_COUNT] = { "
            + ", ".join(names) + " };", "", "#endif", ""]
    (ROOT / "src/game/attract_demo_data.h").write_text("\n".join(out))


if __name__ == "__main__" and sys.argv[1:2] == ["--emit"]:
    emit()
    sys.exit(0)
from pyboy import PyBoy
from PIL import Image
rom, cls, seed, out = sys.argv[1], int(sys.argv[2]), int(sys.argv[3], 0), sys.argv[4]
N = int(sys.argv[5]) if len(sys.argv) > 5 else 1200
WARP = int(sys.argv[6]) if len(sys.argv) > 6 else 0xFF
noi = open(rom[:-4] + ".noi").read()
def sym(n): return int(re.search(rf"DEF {n} 0x([0-9A-F]+)", noi).group(1), 16)
SCR, CNT, KEYS = sym("_loop_current_screen"), sym("_loop_frame_counter"), sym("_input_keys")
MUTE, RS, PL, EN = sym("_attract_mute"), sym("_run_state"), sym("_player"), sym("_entities")
pb = PyBoy(rom, window="null", sound_emulated=False)
m = pb.memory
def s16(a):
    v = m[a] | (m[a + 1] << 8)
    return v - 65536 if v & 0x8000 else v
def tick(n=1):
    for _ in range(n):
        pb.tick(); m[MUTE] = 1; m[RS + 60] = 0xFF; m[RS + 61] = 0xFF
def tap(b, n=4):
    pb.button_press(b); tick(n); pb.button_release(b); tick(2)
tick(1)
while m[SCR] != 1: tick()
tick(30); tap("start"); tick(40)
for _ in range(cls): tap("down"); tick(10)
v = (seed - 1) & 0xFFFF
m[CNT] = v & 0xFF; m[CNT + 1] = v >> 8
m[sym("_title_stage_warp")] = WARP
pb.button_press("a"); tick(1); pb.button_release("a")
print("rs after init:", [m[RS + i] for i in range(8)])
BTN = {0x01: "right", 0x02: "left", 0x04: "up", 0x08: "down", 0x10: "a", 0x20: "b"}
held = 0
def setkeys(k):
    global held
    for bit, name in BTN.items():
        if (k & bit) and not (held & bit): pb.button_press(name)
        if not (k & bit) and (held & bit): pb.button_release(name)
    held = k
trace = []
rec = []           # joypad per loop iteration from the first ROOM/DIALOG iteration
started = False


def on_poll(_ctx):
    # input_poll entry: this iteration ticks loop_current_screen and is about
    # to read the joypad, which holds exactly the bot's buttons. The player
    # position is the previous iteration's result. Ticks and iterations do
    # not line up one to one, so sampling here (not per tick) is exact.
    global started
    if m[SCR] in (5, 10):
        started = True
    if started and len(rec) < N:
        rec.append(held); trace.append((s16(PL + 9), s16(PL + 11), m[SCR]))


pb.hook_register(0, sym("_input_poll"), on_poll, None)
stuck = 0; lastpos = None; detour = 0; detour_k = 0; t = 0
hp_log = []; frames = []
while len(rec) < N:
    # decide keys for the next frame
    k = 0
    if m[SCR] == 5:
        px, py = s16(PL + 9), s16(PL + 11)
        en = []
        for i in range(32):
            b = EN + 28 * i
            if m[b] == 2 and (m[b + 1] & 1):
                en.append((s16(b + 3), s16(b + 7)))
        t += 1
        if detour:
            detour -= 1; k = detour_k
        elif en:
            ex, ey = min(en, key=lambda e: abs(e[0] - px) + abs(e[1] - py))
            dx, dy = ex - px, ey - py
            if abs(dx) <= 6:
                d = 0x04 if dy < 0 else 0x08
                k = d if abs(dy) > 36 else (0x08 if dy < 0 else 0x04) if abs(dy) < 20 else 0
                if k == 0: k = d if (t // 12) % 3 == 0 else 0
                if (t // 4) % 2: k |= 0x10
            elif abs(dy) <= 6:
                d = 0x02 if dx < 0 else 0x01
                k = d if abs(dx) > 36 else (0x01 if dx < 0 else 0x02) if abs(dx) < 20 else 0
                if k == 0: k = d if (t // 12) % 3 == 0 else 0
                if (t // 4) % 2: k |= 0x10
            elif abs(dx) < abs(dy):
                k = 0x02 if dx < 0 else 0x01
            else:
                k = 0x04 if dy < 0 else 0x08
        else:
            k = (0x02 if px > 84 else 0x01) if abs(px - 80) > 4 else 0x04
        pos = (px, py)
        if k & 0x0F and pos == lastpos:
            stuck += 1
            if stuck > 14:
                stuck = 0; detour = 16
                detour_k = 0x01 if (k & 0x0C) else 0x08
                if (t // 50) % 2: detour_k = 0x02 if (k & 0x0C) else 0x04
        else:
            stuck = 0
        lastpos = pos
        if t % 30 == 0: hp_log.append(m[PL + 2])
    setkeys(k)
    tick()
    if started and len(frames) < len(rec) // 4: frames.append(pb.screen.image.convert("RGB").resize((320, 288)).copy())
print("hp", hp_log)
print("screen end", m[SCR], "rooms", m[RS + 0] if False else "")
# RLE
pairs = []
for kk in rec:
    if pairs and pairs[-1][0] == kk and pairs[-1][1] < 255: pairs[-1][1] += 1
    else: pairs.append([kk, 1])
json.dump({"class": cls, "seed": seed, "warp": WARP, "pairs": pairs, "n": len(rec), "trace": trace}, open(out, "w"))
print("pairs", len(pairs))
frames[0].save(out.replace(".json", ".gif"), save_all=True, append_images=frames[1:], duration=67, loop=0)
