#!/usr/bin/env python3
"""Generate src/render/conduit_art.{c,h}: M5a Conduit art.

New art is GPT Image (gpt-image-2.6-sunburst) output quantized to GBC
formats (turret, rolling stone, teleport pad, gold switch, stone groove);
the Stone Jagger, Rime pip and glyph are M1's, the plate, Star bow and key
shaft M4's. Grids are committed in scripts/conduit_art_grids.json.

  python3 scripts/gen_conduit_art.py                 # JSON -> C
  python3 scripts/gen_conduit_art.py --png OUT [s]   # preview sheet
  python3 scripts/gen_conduit_art.py --from-gpt RAW  # re-quantize RAW/*.png

BG (VRAM bank 0, over Riftwild-only ids while the pocket is live; 0 lightest
.. 3 darkest): stone groove (105), teleport pad (106), gold switch (107) and
plate (96), each pad one quadrant mirrored to 2x2. Door 37 / bars 99 come
from lk_bg_art_load (M4/M3 art).
OBJ (VRAM bank 1; 0 transparent, 1 body, 2 outline, 3 highlight):
176 Jagger, 180 turret, 184 stone, 188 switch (gold flash overlay),
192 Star bow, 193 key shaft, 194 Rime pip, 195 aim spark.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_rime_art as m1  # noqa: E402
import gen_rewrite_art as m2  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GRIDS = ROOT / "scripts" / "conduit_art_grids.json"
OBJ16 = ("jagger_idle", "turret", "stone", "switch_obj")
OBJ8 = ("bow_star", "shaft", "pip", "glyph")
BG8 = ("track", "teleport", "switch", "plate")


def from_gpt(raw):
    import numpy as np
    from PIL import Image

    def load(n):
        return np.array(Image.open(Path(raw) / f"{n}.png").convert("RGB")).astype(float)
    g = {"note": "BG: 0 lightest..3 darkest. OBJ: 0 transparent, 1 body, 2 outline, "
                 "3 highlight. Quantized from gpt-image-2.6-sunburst renders by "
                 "scripts/gen_conduit_art.py --from-gpt; Jagger/pip/glyph from M1, "
                 "plate/bow/shaft from M4."}
    r1 = json.loads((ROOT / "scripts/rime_art_grids.json").read_text())
    r4 = json.loads((ROOT / "scripts/lock_art_grids.json").read_text())
    g["jagger_idle"] = r1["jagger_idle"]
    g["pip"] = r1["pip"]
    g["glyph"] = r1["glyph"]
    g["plate"] = r4["wplate"]
    g["bow_star"] = r4["bow_star"]
    g["shaft"] = r4["shaft"]
    g["track"] = m2.quant_bg(load("track8"), 8)
    g["teleport"] = [r[:8] for r in m2.quant_bg(load("teleport16"), 16)[:8]]
    g["switch"] = [r[:8] for r in m2.quant_bg(load("switch16"), 16)[:8]]
    g["turret"] = m2.quant_obj(load("turret16"), 16)
    g["stone"] = m2.quant_obj(load("stone16"), 16)
    g["switch_obj"] = m2.quant_obj(load("switch16"), 16)
    GRIDS.write_text(json.dumps(g, indent=1))


def emit(g):
    bg = sum((m1.tile_bytes(g[n]) for n in BG8), [])
    obj = []
    for name in OBJ16:
        for t in m1.cut(g[name], 2, 2):
            obj += m1.tile_bytes(t)
    for name in OBJ8:
        obj += m1.tile_bytes(g[name])
    c = f"""#pragma bank 22
// Generated by scripts/gen_conduit_art.py from GPT Image art. Do not edit.
#include <gb/gb.h>
#include "core/types.h"
#include "render/conduit_art.h"
#include "render/lock_art.h"

{m1.c_array("cd_bg_tiles", bg)}

static const u8 cd_bg_ids[4] = {{ 105, 106, 107, 96 }};

{m1.c_array("cd_obj_tiles", obj)}

void cd_bg_art_load(void) BANKED {{
    u8 i;
    lk_bg_art_load();               // door 37 and bars 99 (M4 / M3 art)
    VBK_REG = 0;
    for (i = 0; i < 4; ++i)
        set_bkg_data(cd_bg_ids[i], 1, cd_bg_tiles + (u16)i * 16);
}}

void cd_art_load(void) BANKED {{
    VBK_REG = 1;
    set_sprite_data(CD_TILE_JAGGER, {len(obj) // 16}, cd_obj_tiles);
    VBK_REG = 0;
}}
"""
    h = """#ifndef QUINTRA_RENDER_CONDUIT_ART_H
#define QUINTRA_RENDER_CONDUIT_ART_H
// Generated by scripts/gen_conduit_art.py. Bank-1 OBJ tiles.
#include <gb/gb.h>
#define CD_TILE_JAGGER 176   // 2x2 each
#define CD_TILE_TURRET 180
#define CD_TILE_STONE  184
#define CD_TILE_SWITCH 188
#define CD_TILE_BOW    192   // single 8x8 tiles from here (Star bow)
#define CD_TILE_SHAFT  193
#define CD_TILE_PIP    194   // Rime charge
#define CD_TILE_SPARK  195   // turret aim spark
void cd_bg_art_load(void) BANKED;
void cd_art_load(void) BANKED;
#endif
"""
    (ROOT / "src/render/conduit_art.c").write_text(c)
    (ROOT / "src/render/conduit_art.h").write_text(h)


BGP = {"track": [(250, 240, 220), (190, 170, 150), (120, 100, 90), (40, 30, 30)],
       "teleport": [(240, 220, 255), (180, 120, 230), (100, 50, 150), (30, 10, 50)],
       "switch": [(255, 240, 160), (230, 170, 30), (140, 90, 10), (40, 20, 0)],
       "plate": [(255, 240, 200), (220, 180, 100), (140, 90, 40), (40, 20, 10)]}
OBP = {"jagger_idle": m1.PREVIEW_PALS["jagger_idle"],
       "turret": [(0, 0, 0), (150, 140, 190), (40, 30, 60), (250, 200, 80)],
       "stone": [(0, 0, 0), (150, 150, 150), (40, 40, 40), (230, 230, 230)],
       "switch_obj": [(0, 0, 0), (250, 190, 30), (120, 80, 0), (255, 250, 150)],
       "bow_star": [(0, 0, 0), (250, 190, 30), (150, 100, 0), (250, 250, 110)],
       "shaft": [(0, 0, 0), (250, 190, 30), (150, 100, 0), (250, 250, 110)],
       "pip": m1.PREVIEW_PALS["pipes"], "glyph": m1.PREVIEW_PALS["pipes"]}


def preview(g, out, scale=4):
    from PIL import Image
    im = Image.new("RGB", (8 * 20 + 4, 44), (120, 140, 110))
    for i, name in enumerate(BG8):
        grid = g[name]
        for y in range(16):
            for x in range(16):
                if name == "track":
                    gx, gy = x % 8, y % 8
                else:
                    gx, gy = (x if x < 8 else 15 - x), (y if y < 8 else 15 - y)
                im.putpixel((4 + i * 20 + x, 4 + y), BGP[name][int(grid[gy][gx])])
    for i, name in enumerate(OBJ16 + OBJ8):
        for y, row in enumerate(g[name]):
            for x, ch in enumerate(row):
                if ch != "0":
                    im.putpixel((4 + i * 20 + x, 24 + y), OBP[name][int(ch)])
    im.resize((im.width * scale, im.height * scale), Image.NEAREST).save(out)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--from-gpt":
        from_gpt(sys.argv[2])
    g = json.loads(GRIDS.read_text())
    if len(sys.argv) > 2 and sys.argv[1] == "--png":
        preview(g, sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
        return
    emit(g)


if __name__ == "__main__":
    main()
