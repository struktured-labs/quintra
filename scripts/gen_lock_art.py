#!/usr/bin/env python3
"""Generate src/render/lock_art.{c,h}: M4 Lockmire Ferry art.

All art is GPT Image (gpt-image-2.6-sunburst) output quantized to GBC
formats. Grids are committed in scripts/lock_art_grids.json; raw renders
stay out of the repo. The Stone Jagger and the reset plate are M1's, the
gate bars M3's (same graphic, same meaning).

  python3 scripts/gen_lock_art.py                 # JSON -> C
  python3 scripts/gen_lock_art.py --png OUT [s]   # preview sheet
  python3 scripts/gen_lock_art.py --from-gpt RAW  # re-quantize RAW/*.png

BG tiles (VRAM bank 0, over Riftwild-only ids while the pocket is live;
0 lightest .. 3 darkest): belt east (105) and west (106, its mirror), four
scroll frames each; weight plate (107) and pressed (96), one quadrant
mirrored to 2x2; door (37, mirrored across its long axis); bars (99).
OBJ (VRAM bank 1, 176..200; 0 transparent, 1 body, 2 outline, 3 highlight):
176 Jagger, 180 Jagger walk, 184 reset plate, 188 flip plate (east; west
is the X-flip), 192 lure, 196 lure pip, 197 Heart / 198 Star / 199 Moon
bow icons (key bows, door plaques, HUD pips), 200 key shaft.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_rime_art as m1  # noqa: E402
import gen_rewrite_art as m2  # noqa: E402
import gen_kite_art as m3  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GRIDS = ROOT / "scripts" / "lock_art_grids.json"
OBJ16 = ("jagger_idle", "jagger_walk", "plate", "flip", "lure")
OBJ8 = ("lure_pip", "bow_heart", "bow_star", "bow_moon", "shaft")


def shift(grid, dx):
    n = len(grid[0])
    return [r[-dx % n:] + r[:-dx % n] for r in grid]


def mirror(grid):
    return [r[::-1] for r in grid]


def from_gpt(raw):
    import numpy as np
    from PIL import Image

    def load(n):
        return np.array(Image.open(Path(raw) / f"{n}.png").convert("RGB")).astype(float)
    g = {"note": "BG: 0 lightest..3 darkest. OBJ: 0 transparent, 1 body, 2 outline, "
                 "3 highlight. Quantized from gpt-image-2.6-sunburst renders by "
                 "scripts/gen_lock_art.py --from-gpt; Jagger and plate from M1, bars from M3."}
    r1 = json.loads(m1.GRIDS.read_text())
    for k in ("jagger_idle", "jagger_walk", "plate"):
        g[k] = r1[k]
    g["bars"] = json.loads(m3.GRIDS.read_text())["bars"]
    g["belt"] = m2.quant_bg(load("conveyor8"), 8)
    g["door"] = m2.quant_bg(load("door8"), 8)
    w = m2.quant_bg(load("wplate16"), 16)
    g["wplate"] = [r[:8] for r in w[:8]]
    g["flip"] = m2.quant_obj(load("glyph_flip"), 16)
    g["lure"] = m2.quant_obj(load("lure16"), 16)
    g["lure_pip"] = m2.quant_obj(load("lure16"), 8)
    g["bow_heart"] = m2.quant_obj(load("key_heart"), 8)
    g["bow_star"] = m2.quant_obj(load("key_star2"), 8)
    g["bow_moon"] = m2.quant_obj(load("key_moon"), 8)
    g["shaft"] = m2.quant_obj(load("key_shaft"), 8)
    GRIDS.write_text(json.dumps(g, indent=1))


def pressed(grid):
    return ["".join(str(min(3, int(c) + 1)) for c in r) for r in grid]


def emit(g):
    east = [shift(g["belt"], 2 * f) for f in range(4)]
    west = [mirror(t) for t in east]
    bg = (m1.tile_bytes(east[0]) + m1.tile_bytes(west[0]) + m1.tile_bytes(g["wplate"])
          + m1.tile_bytes(pressed(g["wplate"])) + m1.tile_bytes(g["door"])
          + m1.tile_bytes(g["bars"]))
    ids = [105, 106, 107, 96, 37, 99]
    anim = sum((m1.tile_bytes(east[f]) + m1.tile_bytes(west[f]) for f in range(4)), [])
    obj = []
    for name in OBJ16:
        for t in m1.cut(g[name], 2, 2):
            obj += m1.tile_bytes(t)
    for name in OBJ8:
        obj += m1.tile_bytes(g[name])
    c = f"""#pragma bank 24
// Generated by scripts/gen_lock_art.py from GPT Image art. Do not edit.
#include <gb/gb.h>
#include "core/types.h"
#include "render/lock_art.h"

{m1.c_array("lk_bg_tiles", bg)}

static const u8 lk_bg_ids[{len(ids)}] = {{ {", ".join(map(str, ids))} }};

{m1.c_array("lk_belt_frames", anim)}

{m1.c_array("lk_obj_tiles", obj)}

void lk_bg_art_load(void) BANKED {{
    u8 i;
    VBK_REG = 0;
    for (i = 0; i < {len(ids)}; ++i)
        set_bkg_data(lk_bg_ids[i], 1, lk_bg_tiles + (u16)i * 16);
}}

// Scroll both belts one frame (2 px) in their push direction.
void lk_belt_anim(u8 f) BANKED {{
    const u8 *p = lk_belt_frames + (u16)(f & 3) * 32;
    VBK_REG = 0;
    set_bkg_data(105, 1, p);
    set_bkg_data(106, 1, p + 16);
}}

void lk_art_load(void) BANKED {{
    VBK_REG = 1;
    set_sprite_data(LK_TILE_JAGGER, {len(obj) // 16}, lk_obj_tiles);
    VBK_REG = 0;
}}
"""
    h = """#ifndef QUINTRA_RENDER_LOCK_ART_H
#define QUINTRA_RENDER_LOCK_ART_H
// Generated by scripts/gen_lock_art.py. Bank-1 OBJ tiles.
#include <gb/gb.h>
#define LK_TILE_JAGGER      176   // 2x2 each
#define LK_TILE_JAGGER_WALK 180
#define LK_TILE_PLATE       184
#define LK_TILE_FLIP        188   // arrow east; X-flip = west
#define LK_TILE_LURE        192
#define LK_TILE_LURE_PIP    196   // single 8x8 tiles from here
#define LK_TILE_BOW         197   // + 0 Heart, 1 Star, 2 Moon
#define LK_TILE_SHAFT       200
void lk_bg_art_load(void) BANKED;
void lk_belt_anim(u8 f) BANKED;
void lk_art_load(void) BANKED;
#endif
"""
    (ROOT / "src/render/lock_art.c").write_text(c)
    (ROOT / "src/render/lock_art.h").write_text(h)


GREY = [(250, 250, 240), (170, 170, 180), (90, 90, 110), (20, 20, 30)]
BG_PREV = {"belt": GREY, "door": [(255, 200, 120), (200, 120, 60), (110, 60, 30), (30, 16, 10)],
           "wplate": [(255, 240, 200), (220, 180, 100), (140, 90, 40), (40, 20, 10)],
           "bars": m3.BG_PREV["bars"]}
PAL = {"jagger_idle": m1.PREVIEW_PALS["jagger_idle"], "jagger_walk": m1.PREVIEW_PALS["jagger_idle"],
       "plate": m1.PREVIEW_PALS["plate"], "flip": m1.PREVIEW_PALS["pipes"],
       "lure": [(0, 0, 0), (250, 190, 0), (230, 130, 0), (255, 255, 40)],
       "bow_heart": [(0, 0, 0), (250, 100, 100), (130, 30, 30), (250, 210, 50)],
       "bow_star": [(0, 0, 0), (250, 190, 30), (150, 100, 0), (250, 250, 110)],
       "bow_moon": [(0, 0, 0), (230, 230, 215), (105, 105, 120), (245, 165, 150)]}
PAL["lure_pip"] = PAL["lure"]
PAL["shaft"] = PAL["bow_star"]


def preview(g, out, scale=4):
    from PIL import Image
    im = Image.new("RGB", (11 * 20 + 4, 44), (120, 140, 110))
    tiles = [("belt", g["belt"]), ("belt", mirror(g["belt"])), ("wplate", g["wplate"]),
             ("wplate", pressed(g["wplate"])), ("door", g["door"]), ("bars", g["bars"])]
    for i, (name, grid) in enumerate(tiles):
        for y in range(16):
            for x in range(16):
                gx = x % 8 if name != "wplate" else (x if x < 8 else 15 - x)
                gy = y % 8 if name != "wplate" else (y if y < 8 else 15 - y)
                im.putpixel((4 + i * 20 + x, 4 + y), BG_PREV[name][int(grid[gy][gx])])
    for i, name in enumerate(OBJ16 + OBJ8):
        for y, row in enumerate(g[name]):
            for x, ch in enumerate(row):
                if ch != "0":
                    im.putpixel((4 + i * 20 + x, 24 + y), PAL[name][int(ch)])
    im.resize((im.width * scale, im.height * scale), Image.NEAREST).save(out)


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--from-gpt":
        from_gpt(sys.argv[2])
    g = json.loads(GRIDS.read_text())
    if len(sys.argv) > 2 and sys.argv[1] == "--png":
        preview(g, sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
        return
    emit(g)


if __name__ == "__main__":
    main()
