#!/usr/bin/env python3
"""Generate src/render/rime_art.{c,h}: M1 Rime chamber OBJ art (VRAM bank 1).

The art is GPT Image (gpt-image-2.6-sunburst) output, quantized to the
4-colour GBC sprite format. The quantized grids are committed in
scripts/rime_art_grids.json (0 transparent, 1 body, 2 outline/dark,
3 highlight); the raw renders stay out of the repo.

  python3 scripts/gen_rime_art.py                 # JSON -> C
  python3 scripts/gen_rime_art.py --png OUT.png   # 4x preview sheet
  python3 scripts/gen_rime_art.py --from-gpt RAW  # re-quantize RAW/*.png -> JSON

Bank-1 OBJ layout (only the Rime chamber loads it; basilisks, which share
176.., are never spawned there): 176 Jagger idle, 180 Jagger walk,
184 Pipes pedestal, 188 reset plate (each 2x2 row-major), 192 Pipes pip,
193 reset glyph (8x8).
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GRIDS = ROOT / "scripts" / "rime_art_grids.json"
BIG = (("jagger_idle", 176), ("jagger_walk", 180), ("pipes", 184), ("plate", 188))
# Raw render file for each grid (the 16x16-grid redraws read cleanest).
SRC = {"jagger_idle": "jagger16", "jagger_walk": "jagger16_walk", "pipes": "pipes16"}
SMALL = (("pip", 192, "pipes"), ("glyph", 193, "plate"))
# Per-render merge: the Jagger folds its pale rock highlights into the body
# colour (OBJ palette 0 has no grey highlight); pipes and plate keep 3.
DARK_T = 0.5
MERGE_HI = {"jagger_idle": True, "jagger_walk": True}


def tile_bytes(rows):
    out = []
    for row in rows:
        lo = hi = 0
        for x, ch in enumerate(row):
            v = int(ch)
            if v & 1:
                lo |= 0x80 >> x
            if v & 2:
                hi |= 0x80 >> x
        out += [lo, hi]
    return out


def cut(grid, w_tiles, h_tiles):
    return [[grid[ty * 8 + y][tx * 8:tx * 8 + 8] for y in range(8)]
            for ty in range(h_tiles) for tx in range(w_tiles)]


def c_array(name, data):
    lines = [f"static const u8 {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    return "\n".join(lines)


def emit(g):
    data = []
    for name, _base in BIG:
        for t in cut(g[name], 2, 2):
            data += tile_bytes(t)
    for name, _base, _src in SMALL:
        data += tile_bytes(g[name])
    c = f"""#pragma bank 30
// Generated by scripts/gen_rime_art.py from GPT Image art. Do not edit.
#include <gb/gb.h>
#include "render/rime_art.h"

BANKREF(rime_art_load)

{c_array("rime_tiles", data)}

void rime_art_load(void) BANKED {{
    VBK_REG = 1;
    set_sprite_data(RIME_TILE_JAGGER, {len(data) // 16}, rime_tiles);
    VBK_REG = 0;
}}
"""
    h = """// Generated by scripts/gen_rime_art.py. Do not edit.
#ifndef QUINTRA_RIME_ART_H
#define QUINTRA_RIME_ART_H
#include <gb/gb.h>
#include "core/types.h"

/* VRAM bank-1 OBJ tiles (prop | 0x08); 2x2 blocks are TL, TR, BL, BR. */
#define RIME_TILE_JAGGER      176
#define RIME_TILE_JAGGER_WALK 180
#define RIME_TILE_PIPES       184
#define RIME_TILE_PLATE       188
#define RIME_TILE_PIP         192
#define RIME_TILE_GLYPH       193

BANKREF_EXTERN(rime_art_load)
void rime_art_load(void) BANKED;

#endif
"""
    (ROOT / "src/render/rime_art.c").write_text(c)
    (ROOT / "src/render/rime_art.h").write_text(h)


PREVIEW_PALS = {
    "jagger_idle": [(0, 0, 0), (230, 230, 214), (107, 107, 123), (247, 165, 148)],
    "jagger_walk": [(0, 0, 0), (230, 230, 214), (107, 107, 123), (247, 165, 148)],
    "frozen": [(0, 0, 0), (66, 99, 230), (33, 49, 165), (165, 198, 255)],
    "pipes": [(0, 0, 0), (66, 99, 230), (33, 49, 165), (165, 198, 255)],
    "pip": [(0, 0, 0), (66, 99, 230), (33, 49, 165), (165, 198, 255)],
    "plate": [(0, 0, 0), (255, 198, 33), (148, 99, 0), (255, 255, 115)],
    "glyph": [(0, 0, 0), (255, 198, 33), (148, 99, 0), (255, 255, 115)],
}


def preview(g, out, scale=4):
    from PIL import Image
    items = [("jagger_idle", "jagger_idle"), ("jagger_walk", "jagger_walk"),
             ("jagger_idle", "frozen"), ("pipes", "pipes"), ("plate", "plate"),
             ("pip", "pip"), ("glyph", "glyph")]
    im = Image.new("RGB", (len(items) * 20 + 4, 24), (120, 140, 110))
    for i, (name, pal) in enumerate(items):
        for y, row in enumerate(g[name]):
            for x, ch in enumerate(row):
                if ch != "0":
                    im.putpixel((4 + i * 20 + x, 4 + y), PREVIEW_PALS[pal][int(ch)])
    im.resize((im.width * scale, im.height * scale), Image.NEAREST).save(out)


def from_gpt(raw):
    import numpy as np
    from PIL import Image

    def classify(a, merge_hi):
        a = a.astype(int)
        lum = (a[..., 0] * 3 + a[..., 1] * 6 + a[..., 2]) / 10
        spread = a.max(-1) - a.min(-1)
        c = np.full(lum.shape, 1)
        white = (lum > 232) & (spread < 30)
        c[lum < 70] = 2
        dark_canvas = c[0, 0] == 2 and c[0, -1] == 2
        c[white] = 3 if dark_canvas else 0
        # Flood the background from the border through whichever class the
        # corners are (white renders, or a black canvas behind black lines).
        from collections import deque
        h, w = c.shape
        bgc = 2 if c[0, 0] == 2 and c[0, -1] == 2 else 0
        # Work on a quarter-scale mask; dilating the foreground first keeps
        # the flood out of the one-pixel dark seams between body parts.
        from PIL import Image as _I, ImageFilter
        fg = _I.fromarray(((c != bgc) * 255).astype("uint8")).resize((w // 4, h // 4))
        fg = np.array(fg.filter(ImageFilter.MaxFilter(13))) > 0
        sh, sw = fg.shape
        seen = np.zeros(fg.shape, bool)
        q = deque([(0, 0), (0, sw - 1), (sh - 1, 0), (sh - 1, sw - 1)])
        while q:
            y, x = q.popleft()
            if y < 0 or x < 0 or y >= sh or x >= sw or seen[y, x] or fg[y, x]:
                continue
            seen[y, x] = True
            q.extend(((y + 1, x), (y - 1, x), (y, x + 1), (y, x - 1)))
        # Undo the dilation margin: background is the flooded zone grown back
        # to the true silhouette edge (only bg-class pixels flip to 0).
        grow = np.array(_I.fromarray((seen * 255).astype("uint8")).filter(
            ImageFilter.MaxFilter(13)).resize((w, h))) > 0
        c[grow & (c == bgc)] = 0
        if merge_hi:
            c[c == 3] = 1
        else:
            body = lum[(c == 1)]
            cut_hi = np.percentile(body, 70) if body.size else 200
            c[(c == 1) & (lum >= cut_hi)] = 3
        return c

    def reduce(c, n):
        ys, xs = np.where(c != 0)
        y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
        s = max(y1 - y0, x1 - x0)
        cy, cx = (y0 + y1) // 2, (x0 + x1) // 2
        pad = np.zeros((c.shape[0] + 2 * s, c.shape[1] + 2 * s), int)
        pad[s:s + c.shape[0], s:s + c.shape[1]] = c
        crop = pad[cy + s - s // 2:cy + s - s // 2 + s, cx + s - s // 2:cx + s - s // 2 + s]
        out = np.zeros((n, n), int)
        for y in range(n):
            for x in range(n):
                blk = crop[y * s // n:(y + 1) * s // n, x * s // n:(x + 1) * s // n]
                cnt = np.bincount(blk.ravel(), minlength=4) / blk.size
                if cnt[0] > 0.55:
                    continue
                nz = cnt.copy()
                nz[0] = 0
                if cnt[2] >= DARK_T:
                    out[y, x] = 2
                else:
                    out[y, x] = int(np.argmax(nz))
        # 1-px silhouette outline in the dark colour.
        o = out.copy()
        for y in range(n):
            for x in range(n):
                if not out[y, x]:
                    continue
                for dy, dx in ((-1, 0), (1, 0), (0, -1), (0, 1)):
                    yy, xx = y + dy, x + dx
                    if not (0 <= yy < n and 0 <= xx < n) or not out[yy, xx]:
                        o[y, x] = 2
        return o

    rows = lambda a: ["".join(str(int(v)) for v in r) for r in a]
    g = {"note": "Colour indices (0 transparent, 1 body, 2 outline/dark, 3 highlight) "
                 "quantized from gpt-image-2.6-sunburst renders by "
                 "scripts/gen_rime_art.py --from-gpt."}
    for name, _b in BIG:
        a = np.array(Image.open(Path(raw) / f"{SRC.get(name, name)}.png").convert("RGB"))
        g[name] = rows(reduce(classify(a, MERGE_HI.get(name, False)), 16))
    for name, _b, src in SMALL:
        a = np.array(Image.open(Path(raw) / f"{SRC.get(src, src)}.png").convert("RGB"))
        g[name] = rows(reduce(classify(a, False), 8))
    GRIDS.write_text(json.dumps(g, indent=1))


def main():
    if len(sys.argv) > 2 and sys.argv[1] == "--from-gpt":
        from_gpt(sys.argv[2])
    g = json.loads(GRIDS.read_text())
    if len(sys.argv) > 2 and sys.argv[1] == "--png":
        preview(g, sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 4)
        return
    emit(g)


if __name__ == "__main__":
    main()
