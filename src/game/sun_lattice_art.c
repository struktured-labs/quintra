#define SL_ANIM_STEP  6    // game frames per animation frame
#define SL_GLINT_STEP 16   // game frames between reflection sparkles

static u8 sl_anim_div;
static u8 sl_anim_frame;
static u8 sl_glint_div;
static u8 sl_glint_at;

static u8 beam_bit(const u8 *b, u16 c) {
    return (u8)(b[(u8)(c >> 3)] & (u8)(1u << (u8)(c & 7)));
}

// A reflector the light actually reaches: a beam cell on any side.
static u8 fixture_in_beam(u8 i) {
    u8 x = sl_x[i], y = sl_y[i];
    u16 c = (u16)((u16)y * SL_MAP_W + x);
    return (x > 0 && beam_bit(sl_beam_h, (u16)(c - 1)))
        || (x < SL_MAP_W - 1 && beam_bit(sl_beam_h, (u16)(c + 1)))
        || (y > 0 && beam_bit(sl_beam_v, (u16)(c - SL_MAP_W)))
        || (y < SL_MAP_H - 1 && beam_bit(sl_beam_v, (u16)(c + SL_MAP_W)));
}

// Per-frame, and deliberately cheap: three 16-byte tile uploads every sixth
// frame, one more three frames later, and one short-lived spark sprite at a
// time. No map cells are rewritten, so beam logic and the trace are
// untouched. The tiles live in VRAM bank 1 (see sun_lattice.c).
void sun_lattice_animate(void) BANKED {
    u8 n;
    if (++sl_anim_div == SL_ANIM_STEP) {
        sl_anim_div = 0;
        sl_anim_frame = (u8)((sl_anim_frame + 1) & 3);
        VBK_REG = 1;
        set_bkg_data(SUN_LATTICE_TILE + 4, 3, sl_beam_anim[sl_anim_frame]);
        VBK_REG = 0;
    } else if (sl_anim_div == SL_ANIM_STEP / 2) {
        VBK_REG = 1;
        set_bkg_data(SUN_LATTICE_TILE + 1, 1, sl_vane_anim[sl_anim_frame]);
        VBK_REG = 0;
    }
    if (++sl_glint_div < SL_GLINT_STEP) return;
    sl_glint_div = 0;
    if (sl_glint_at >= sl_n) sl_glint_at = 0;
    // Glint on the next mirror or wedge the light is bouncing off.
    for (n = 0; n < sl_n; ++n) {
        u8 i = sl_glint_at;
        u8 k = sl_kind[i];
        if (++sl_glint_at >= sl_n) sl_glint_at = 0;
        if ((k == SLK_VANE || k == SLK_FIXED || k == SLK_BIFROST)
            && fixture_in_beam(i)) {
            fx_spawn(SPR_FX_IMPACT, 0, (i16)((u16)sl_x[i] << 3),
                (i16)((u16)sl_y[i] << 3), 5);
            return;
        }
    }
}
