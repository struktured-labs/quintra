void boss_projectile_load_art(void) BANKED {
    static const u16 violet[4] = {
        BGR555(0,0,0), BGR555(10,3,15), BGR555(28,8,27), BGR555(31,26,31)
    };
    set_sprite_data(208, 16, shot_tiles);
    palette_obj_load(3, violet);
}

u8 boss_projectile_draw(entity_t *e, u8 oam, u8 x, u8 y) BANKED {
    if (!(e->flags & EF_BOSS_PROJECTILE)) {
        if (e->ai_data[6] != PROJ_AUX_FUSE_BOMB) return hookshot_draw(e,oam,x,y);
        if (oam>=40) return oam;
        set_sprite_tile(oam,e->sprite_tile); set_sprite_prop(oam,e->palette);
        move_sprite(oam,x,y); return oam+1;
    }
    u8 i, count = e->ai_data[4] == BOSS_SHAPE_SEED
        || e->ai_data[4] == BOSS_SHAPE_CRESCENT ? 4
        : e->ai_data[4] == BOSS_SHAPE_BOLT ? 2 : 1;
    if (oam + count > 40) return oam;
    for (i = 0; i < count; ++i) {
        set_sprite_tile(oam, e->sprite_tile + i);
        set_sprite_prop(oam, e->palette);
        move_sprite(oam, x + ((i & 1) << 3), y + ((i >> 1) << 3));
        oam++;
    }
    return oam;
}
