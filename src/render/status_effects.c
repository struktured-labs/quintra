void status_effects_load(void) BANKED {
    u8 tile[16],i,y;
    VBK_REG=1;
    for (i=0;i<14;++i) {
        for (y=0;y<8;++y) {
            tile[y*2]=glyphs[i][y];
            tile[y*2+1]=glyphs[i][y] & (u8)(glyphs[i][y]<<1);
        }
        set_sprite_data(224+i,1,tile);
    }
    VBK_REG=0;
}

void status_effect(u8 kind,u8 palette,i16 x,i16 y) BANKED {
    u8 i,free=0,count=0;
    if (!kind || kind>=QSTATUS_COUNT) return;
    for (i=0;i<MAX_ENTITIES;++i) {
        if (!(entities[i].flags&EF_ACTIVE)) free++;
        else if (entities[i].type==ENT_FX && (entities[i].palette&8)) count++;
    }
    if (free<=6 || count>=3) return;
    i=fx_spawn(223+kind,palette|8,x,y-8,12);
    if (i!=0xFF) {
        entities[i].ai_data[6]=PROJ_AUX_BEAM_TRAIL;
        entities[i].vy=(kind==QSTATUS_BLEED) ? 1
            : (kind==QSTATUS_POISON || kind==QSTATUS_BURN || kind==QSTATUS_REGEN) ? -1 : 0;
        entities[i].vx=kind==QSTATUS_HASTE ? -1 : 0;
    }
}
