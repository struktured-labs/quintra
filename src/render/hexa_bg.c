static void put_tile(u8 x, u8 y, u8 tile) {
    VBK_REG = 0;
    set_bkg_tiles(x, y, 1, 1, &tile);
}

static void put_attr(u8 x, u8 y, u8 attr) {
    VBK_REG = 1;
    set_bkg_tiles(x, y, 1, 1, &attr);
    VBK_REG = 0;
}

static void load_body_colors(void) {
    palette_bg_load(0, floor_bg);
    palette_bg_load(5, body_bg);
    palette_obj_load(3, shot_warm);
    palette_obj_load(4, shot_cool);
    palette_obj_load(5, limb_obj);
}

static void tint_window(u8 limb, u8 pal) {
    u8 r, c;
    for (r = 0; r < 4; ++r) {
        for (c = 0; c < 4; ++c) {
            u8 x = (u8)(win_x[limb] + c);
            u8 y = (u8)(win_y[limb] + r);
            u8 idx = (u8)((y - 1) * 16 + (x - 2));
            if (!hexa_bg_map[idx]) continue;
            put_attr(x, y, (u8)((hexa_bg_attr[idx] & 0x68) | pal));
        }
    }
}

static void core_tiles(u8 phase) {
    u8 i;
    u8 id = (u8)(HEXA_BG_CC + phase);
    if (phase > 2) id = HEXA_BG_CP;
    for (i = 0; i < 4; ++i) {
        u8 idx = core_i[i];
        u8 x = (u8)((idx & 15) + 2);
        u8 y = (u8)((idx >> 4) + 1);
        room_tilemap[y][x] = id;
        put_tile(x, y, id);
    }
}

static void core_attr(u8 pal) {
    u8 i;
    for (i = 0; i < 4; ++i) {
        u8 idx = core_i[i];
        u8 x = (u8)((idx & 15) + 2);
        u8 y = (u8)((idx >> 4) + 1);
        put_attr(x, y, (u8)((hexa_bg_attr[idx] & 0x68) | pal));
    }
}

static u8 core_pal(u8 spotlight, u8 phase) {
    if (spotlight < 5 || phase >= 1) return 6;
    return 5;
}

void hexa_bg_prepare(void) BANKED {
    u8 x, y, i;
    VBK_REG = 1;
    set_bkg_data(HEXA_BG_TILE, HEXA_BG_COUNT, hexa_bg_tiles);
    VBK_REG = 0;
    for (y = 0; y < ROOM_H; ++y) {
        for (x = 0; x < ROOM_W; ++x) {
            u8 tile = BGT_FLOOR;
            if (x == 0 || y == 0 || x == (ROOM_W - 1)) tile = BGT_WALL;
            else if (x >= 2 && x <= 17 && y >= 1 && y <= 13) {
                i = (u8)((y - 1) * 16 + (x - 2));
                if (hexa_bg_map[i]) tile = hexa_bg_map[i];
            }
            room_tilemap[y][x] = tile;
        }
    }
}

void hexa_bg_stamp(u8 spotlight, u8 phase) BANKED {
    u8 x, y, i, attr;
    load_body_colors();
    if (spotlight < 5) palette_bg_load(6, &spot_bg[spotlight * 4]);
    else if (phase >= 1) palette_bg_load(6, core_bg);
    for (y = 1; y <= 13; ++y) {
        for (x = 2; x <= 17; ++x) {
            i = (u8)((y - 1) * 16 + (x - 2));
            attr = hexa_bg_attr[i];
            if (spotlight < 5 && hexa_bg_map[i]) {
                u8 lx = win_x[spotlight];
                u8 ly = win_y[spotlight];
                if (x >= lx && x < (u8)(lx + 4) && y >= ly && y < (u8)(ly + 4))
                    attr = (u8)((attr & 0x68) | 6);
            }
            put_attr(x, y, attr);
        }
    }
    core_tiles(phase);
    core_attr(core_pal(spotlight, phase));
}

void hexa_bg_retint(u8 previous, u8 next, u8 phase) BANKED {
    if (previous < 5) tint_window(previous, 5);
    if (next < 5) {
        palette_bg_load(6, &spot_bg[next * 4]);
        tint_window(next, 6);
    } else if (phase >= 1) {
        palette_bg_load(6, core_bg);
    }
    core_attr(core_pal(next, phase));
}

void hexa_bg_set_phase(u8 phase, u8 spotlight) BANKED {
    if (spotlight >= 5 && phase >= 1) palette_bg_load(6, core_bg);
    core_tiles(phase);
    core_attr(core_pal(spotlight, phase));
}

void hexa_bg_core_blink(u8 dim) BANKED {
    core_attr(dim ? 5 : 6);
}
