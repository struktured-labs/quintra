void music_read_variant(u8 stage, u8 boss, music_variant_t *out) BANKED {
    // Keep the conditional on pointers. SDCC 4.x miscompiles a conditional
    // expression whose operands are whole structs by treating the struct's
    // first pointer member as memcpy's source address.
    const music_variant_t *source = boss ?
        &boss_music[stage] : &stage_music[stage];
    *out = *source;
}

void music_load_wave(u8 shape) BANKED {
    u8 i;
    if (shape >= MUSIC_WAVE_COUNT) shape = 0;
    NR30_REG = 0x00;
    for (i = 0; i < 16; ++i)
        *((volatile u8 *)(0xFF30 + i)) = wave_shape[shape][i];
    NR30_REG = 0x80;
}

static u8 scale_has(u16 scale, u8 pitch) {
    while (pitch >= 12) pitch -= 12;
    return (scale & (u16)(1u << pitch)) != 0;
}

void music_prepare_harmony(u16 scale, u8 *out) BANKED {
    u8 root;
    for (root = 0; root < 12; ++root) {
        u8 pitch;
        u8 offset = (u8)(root * 3);
        u8 third = scale_has(scale, (u8)(root + 4)) ? 4 : 3;
        u8 fifth = scale_has(scale, (u8)(root + 7)) ? 7 : 6;
        out[offset] = (u8)(T_C5 + root);
        pitch = root + third;
        if (pitch > 16) pitch -= 12;
        out[offset + 1] = (u8)(T_C5 + pitch);
        pitch = root + fifth;
        if (pitch > 16) pitch -= 12;
        out[offset + 2] = (u8)(T_C5 + pitch);
    }
}
